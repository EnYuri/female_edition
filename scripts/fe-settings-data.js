function feRegisterSetting(key, onChange) {
  const definition = FE_SETTING_DEFINITIONS[key];
  if (!definition) throw new Error(`Unknown female_edition setting: ${key}`);
  // Fresh nested objects prevent core or another consumer from mutating the source.
  const options = structuredClone({ ...definition, type: undefined, default: FE_DEFAULTS[key] });
  if (definition.type) options.type = definition.type;
  else delete options.type;
  if (onChange) options.onChange = onChange;
  return game.settings.register("female_edition", key, options);
}

